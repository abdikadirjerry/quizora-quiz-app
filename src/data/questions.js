function normalizeCategory(value = "") {
  const normalized = value
    .toLowerCase()
    .trim()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

  return CATEGORY_ALIASES[normalized] ?? normalized;
}

export function getQuestionsForCategory(categoryId, categoryName) {
  const category = normalizeCategory(categoryName || categoryId);

  const matchingQuestions = QUESTION_BANK.filter(
    (question) => question.category === category,
  );

  return matchingQuestions.length > 0
    ? matchingQuestions
    : QUESTION_BANK.filter(
        (question) => question.category === "general-knowledge",
      );
}
